void I18n::set_lang(Lang lang) {
    lang_ = lang;
}

const std::wstring& I18n::get(const std::wstring& key) const {
    static const auto zh = make_zh();
    static const auto en = make_en();
    static const std::wstring empty;
    const auto& table = is_zh() ? zh : en;
    const auto it = table.find(key);
    return it == table.end() ? empty : it->second;
}

std::wstring I18n::t(const std::wstring& key) const {
    const auto& value = get(key);
    return value.empty() ? key : value;
}

std::wstring I18n::t(const std::wstring& key,
                     const std::unordered_map<std::wstring, std::wstring>& values) const {
    return format_w(t(key), values);
}

