std::unordered_map<std::wstring, std::wstring> make_zh() {
    std::unordered_map<std::wstring, std::wstring> map;
    map.reserve(std::size(kEntries));
    for (const auto& entry : kEntries) map[entry.key] = entry.zh;
    return map;
}

std::unordered_map<std::wstring, std::wstring> make_en() {
    std::unordered_map<std::wstring, std::wstring> map;
    map.reserve(std::size(kEntries));
    for (const auto& entry : kEntries) map[entry.key] = entry.en;
    return map;
}

